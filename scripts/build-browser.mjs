// Keep the maintainable ES-module sources; ship a classic script for file:// use.
import {readFileSync, writeFileSync} from 'node:fs';
const root = new URL('../', import.meta.url);
const rules = readFileSync(new URL('sniper-elite/rules.js', root), 'utf8').replace(/^export /gm, '');
const app = readFileSync(new URL('sniper-elite/app.js', root), 'utf8')
  .replace(/^import .* from '\.\/rules\.js';\n/, '')
  .replace('import.meta.url', 'document.currentScript.src');
const bundle = '// Generated by npm run build; edit rules.js and app.js instead.\n(() => {\n\"use strict\";\n' + rules + '\n' + app + '\n})();\n';
writeFileSync(new URL('sniper-elite/browser.js', root), bundle);
